"""Phase 4: renders evaluation_report.md from a benchmark_runner.summarize()
result plus the regression-suite score. Presentation only - computes
nothing itself beyond formatting percentages and reading
data/corpus_metadata.json for the corpus version line.
"""

import json
from datetime import datetime, timezone
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
CORPUS_METADATA_FILE = BASE_DIR / "data" / "corpus_metadata.json"
REPORT_FILE = BASE_DIR / "evaluation_report.md"


def _pct(value):
    return f"{value * 100:.1f}%" if value is not None else "n/a"


def _corpus_version():

    try:
        with CORPUS_METADATA_FILE.open("r", encoding="utf-8") as f:
            data = json.load(f)
        return data.get("retrieved_at", "unknown")
    except Exception:
        return "unknown (data/corpus_metadata.json not found)"


def generate_report(benchmark_summary, regression_summary=None):

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    lines = []

    lines.append("# WLU Chatbot Evaluation Report")
    lines.append("")
    lines.append(f"**Generated:** {now}")
    lines.append(f"**Corpus version (data/corpus_metadata.json retrieved_at):** {_corpus_version()}")
    lines.append("")
    lines.append(
        "Benchmark questions and their expected answers are stored in "
        "`evaluation/benchmark.json` and never generated by an LLM at "
        "evaluation time - every result below is a deterministic string-"
        "match against pre-authored ground truth."
    )
    lines.append("")

    if regression_summary is not None:
        lines.append("## Regression Suite")
        lines.append("")
        lines.append(
            f"**{regression_summary['passed']}/{regression_summary['total']}** "
            f"checks passed (`src/evaluate.py`'s existing 226-check suite)."
        )
        lines.append("")

    lines.append("## Overall Benchmark Metrics")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("|---|---|")
    lines.append(f"| Total Questions | {benchmark_summary['total_questions']} |")
    lines.append(f"| Answer Accuracy | {_pct(benchmark_summary['answer_accuracy'])} |")
    lines.append(
        f"| Citation Accuracy | {_pct(benchmark_summary['citation_accuracy'])} "
        f"(n={benchmark_summary['citation_checked_count']}) |"
    )
    lines.append(
        f"| Hallucination Rate | {_pct(benchmark_summary['hallucination_rate'])} "
        f"(n={benchmark_summary['decline_expected_count']} out-of-scope/decline-expected questions) |"
    )
    lines.append(
        f"| Retrieval Success Rate | {_pct(benchmark_summary['retrieval_success_rate'])} "
        f"(n={benchmark_summary['retrieval_expected_count']}) |"
    )
    lines.append(
        f"| Structured Retrieval Accuracy | {_pct(benchmark_summary['structured_retrieval_accuracy'])} "
        f"(n={benchmark_summary['structured_count']}) |"
    )
    lines.append(
        f"| Hybrid Retrieval Accuracy | {_pct(benchmark_summary['hybrid_retrieval_accuracy'])} "
        f"(n={benchmark_summary['hybrid_count']}) |"
    )
    lines.append(
        f"| Average Response Time | {benchmark_summary['average_response_time']:.2f}s |"
    )
    lines.append("")

    lines.append("## Category Breakdown")
    lines.append("")
    lines.append("| Category | Passed | Total | Accuracy |")
    lines.append("|---|---|---|---|")
    for category, stats in sorted(benchmark_summary["category_breakdown"].items()):
        lines.append(
            f"| {category} | {stats['passed']} | {stats['total']} | "
            f"{_pct(stats['accuracy'])} |"
        )
    lines.append("")

    lines.append("## Retrieval Statistics")
    lines.append("")
    lines.append(
        f"- Questions routed to **structured retrieval**: "
        f"{benchmark_summary['structured_count']} "
        f"(accuracy {_pct(benchmark_summary['structured_retrieval_accuracy'])})"
    )
    lines.append(
        f"- Questions routed to **hybrid/vector retrieval**: "
        f"{benchmark_summary['hybrid_count']} "
        f"(accuracy {_pct(benchmark_summary['hybrid_retrieval_accuracy'])})"
    )
    lines.append(
        f"- Questions expecting a graceful decline (out-of-scope/fabricated): "
        f"{benchmark_summary['decline_expected_count']}"
    )
    lines.append("")

    failed = benchmark_summary["failed_questions"]

    lines.append(f"## Failed Questions ({len(failed)})")
    lines.append("")

    if not failed:
        lines.append("None - every benchmark question passed.")
    else:
        lines.append("| ID | Category | Question | Response Type | Failure Reason |")
        lines.append("|---|---|---|---|---|")
        for f in failed:
            question = f["question"].replace("|", "\\|")
            reason = (f["failure_reason"] or "").replace("|", "\\|")
            lines.append(
                f"| {f['id']} | {f['category']} | {question} | "
                f"{f['response_type']} | {reason} |"
            )

    lines.append("")

    report_text = "\n".join(lines)

    REPORT_FILE.write_text(report_text, encoding="utf-8")

    return REPORT_FILE
