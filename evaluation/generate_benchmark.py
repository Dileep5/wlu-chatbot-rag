# -----------------------------

def generate_conversation():
    items = []

    for q in ["hi", "hello", "good morning"]:
        items.append(_item(
            "CONV", "Conversation / Follow-up", [q],
            expected_keywords=["Wilfrid Laurier", "help"], match_mode="any",
            requires_retrieval=False,
        ))

    for q in ["how are you", "who are you", "what can you do", "thank you"]:
        items.append(_item(
            "CONV", "Conversation / Follow-up", [q],
            expected_keywords=[], requires_retrieval=False,
        ))

    course_row = _query(
        "data/courses.db",
        "SELECT course_code FROM courses WHERE course_name IS NOT NULL "
        "ORDER BY course_code LIMIT 1"
    )
    code = course_row[0][0] if course_row else "CP104"

    items.append(_item(
        "CONV", "Conversation / Follow-up",
        [f"What is {code}?", "tell me more"],
        expected_keywords=[code], expect_citation=True,
    ))
    items.append(_item(
        "CONV", "Conversation / Follow-up",
        [f"What is {code}?", "Does it have prerequisites?"],
        expected_keywords=[code, "prerequisite"], match_mode="any",
    ))
    items.append(_item(
        "CONV", "Conversation / Follow-up",
        ["Tell me about the Economics department.", "tell me more"],
        expected_keywords=["Economics"],
    ))
    items.append(_item(
        "CONV", "Conversation / Follow-up",
        ["Tell me about the Honours BA Economics program.", "explain"],
        expected_keywords=["Economics"],
    ))
    items.append(_item(
        "CONV", "Conversation / Follow-up",
        ["What is policy 12.2?", "tell me more"],
        expected_keywords=["12.2"],
    ))
    items.append(_item(
        "CONV", "Conversation / Follow-up",
        ["tell me more"],
        expected_keywords=[], requires_retrieval=False,
    ))
    items.append(_item(
        "CONV", "Conversation / Follow-up",
        ["Who is Shohini Ghose?", "what does she research?"],
        expected_keywords=["Ghose", "research"], match_mode="any",
    ))
    items.append(_item(
        "CONV", "Conversation / Follow-up",
        ["What is the Honours BSc Computer Science program?", "what are the admission requirements?"],
        expected_keywords=["admission", "requirement", "Computer Science"], match_mode="any",
    ))

    while len(items) < 18:
        items.append(_item(
            "CONV", "Conversation / Follow-up", ["hey"],
            expected_keywords=["Wilfrid Laurier", "help"], match_mode="any",
            requires_retrieval=False,
        ))

    return items[:18]


# -----------------------------
# Unsupported / Out-of-domain (22) - genuinely off-topic questions plus
# fabricated WLU-shaped entities (fake course codes, names, policy
# numbers). Every one of these expects a graceful decline, never a
# confident fabricated answer.
# -----------------------------

def generate_unsupported():
    # Deliberately excludes harmless small talk ("tell me a joke", "how
    # are you") - app.py's is_conversation() path is *designed* to
    # handle those conversationally (see generate_chat_response()'s own
    # system prompt, which lists "tell me a joke" as an example), so
    # expecting a decline there would be testing against the system's
    # own intended behavior, not a real gap. Only genuinely off-topic
    # (no WLU connection at all) or fabricated-entity questions belong
    # here.
    off_topic = [
        "What is the capital of France?",
        "What's the weather like today?",
        "Who won the Super Bowl last year?",
        "Can you write me a Python script to sort a list?",
        "What is the best pizza topping?",
        "How do I fix my car's engine?",
        "What is the population of Tokyo?",
        "What is the airspeed velocity of an unladen swallow?",
        "What's the stock price of Apple?",
        "How do I bake a chocolate cake?",
        "What is the tuition at the University of Toronto?",
    ]
    fabricated = [
        "What is ZZ999?",
        "Tell me about the Doctor of Underwater Basket Weaving program.",
        "Who is Professor Xavier Nonexistent?",
        "What is policy 99.9?",
        "Tell me about the Department of Time Travel Studies.",
        "What is CP000000?",
        "Who teaches XX123?",
        "What is the Bachelor of Dragon Riding program?",
        "Tell me about policy 0.0.",
        "Who is Dr. Fictional Person at WLU?",
        "What are the requirements for the Master of Imaginary Science?",
    ]
    items = []
    for q in off_topic + fabricated:
        items.append(_item(
            "UNSUPPORTED", "Unsupported / Out-of-domain", [q],
            expect_decline=True, requires_retrieval=False,
        ))
    return items


def main():

    items = (
        generate_courses()
        + generate_faculty()
        + generate_programs()
        + generate_departments()
        + generate_policies()
        + generate_deadlines()
        + generate_campus_services()
        + generate_student_services()
        + generate_faq()
        + generate_conversation()
        + generate_unsupported()
    )

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)

    with OUTPUT_FILE.open("w", encoding="utf-8") as f:
        json.dump(items, f, indent=2)

    print(f"Generated {len(items)} benchmark questions -> {OUTPUT_FILE}")

    from collections import Counter
    counts = Counter(item["category"] for item in items)
    for category, count in counts.items():
        print(f"  {category}: {count}")


if __name__ == "__main__":
    main()
