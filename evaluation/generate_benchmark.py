"""Generates evaluation/benchmark.json (Phase 4).

One-time/re-runnable generator, not part of the live evaluation path -
evaluate.py only ever reads the resulting benchmark.json, never this
script. Kept for transparency/reproducibility: every structured-category
question (Courses/Faculty/Programs/Departments/Policies) is pulled
directly from the real, live structured databases with deterministic
ORDER BY/OFFSET (never RANDOM()), so re-running this script against the
same data/ produces an identical benchmark.json. Expected answers are
never generated by an LLM - every expected_keywords/expect_decline/
expected_source_contains value is authored here, stored as ground truth,
and checked later by plain deterministic string matching.
"""

import json
import sqlite3
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
OUTPUT_FILE = BASE_DIR / "evaluation" / "benchmark.json"

sys.path.insert(0, str(BASE_DIR / "src"))
import retriever  # noqa: E402 - generator-time validation only, not imported by evaluate.py


def _round_trips(question, expected_keyword):
    """True if actually asking `question` right now produces a response
    containing `expected_keyword` - validated directly against
    retriever.py so a candidate whose stored DB name doesn't survive the
    real fuzzy-matching tiers (compound/joint-program names, ambiguous
    department titles, etc.) is caught and skipped at generation time,
    never silently baked into the benchmark as a question the live
    system doesn't actually answer the way its own name suggests."""

    try:
        result = retriever.structured_search(question, None)
        content = result[0] if result else None
        if not content:
            content = retriever.hybrid_search(question, None)[0]
    except Exception:
        return False

    return expected_keyword.lower() in (content or "").lower()

_id_counters = {}


def _next_id(prefix):
    _id_counters[prefix] = _id_counters.get(prefix, 0) + 1
    return f"{prefix}_{_id_counters[prefix]:03d}"


def _item(
    prefix, category, turns, expected_keywords=None, match_mode="any",
    expect_decline=False, expect_citation=False, expected_source_contains=None,
    requires_retrieval=True,
):
    return {
        "id": _next_id(prefix),
        "category": category,
        "turns": turns,
        "expected_keywords": expected_keywords or [],
        "match_mode": match_mode,
        "expect_decline": expect_decline,
        "expect_citation": expect_citation,
        "expected_source_contains": expected_source_contains,
        "requires_retrieval": requires_retrieval,
    }


def _query(db_path, sql):
    conn = sqlite3.connect(str(BASE_DIR / db_path))
    cursor = conn.cursor()
    cursor.execute(sql)
    rows = cursor.fetchall()
    conn.close()
    return rows


# -----------------------------
# Courses (22) - real course_code/course_name/source_url, spread across
# the alphabet via fixed OFFSETs (deterministic, not RANDOM()).
# -----------------------------

def generate_courses(target=22):
    items = []
    rows = []
    for offset in range(0, 3000, 150):
        rows += _query(
            "data/courses.db",
            "SELECT course_code, course_name FROM courses "
            "WHERE course_name IS NOT NULL AND source_url IS NOT NULL "
            f"ORDER BY course_code LIMIT 2 OFFSET {offset}"
        )
    seen = set()
    for code, name in rows:
        if len(items) >= target:
            break
        if code in seen:
            continue
        seen.add(code)
        question = f"What is {code}?"
        if not _round_trips(question, code):
            continue
        items.append(_item(
            "COURSE", "Courses", [question],
            expected_keywords=[code], expect_citation=True,
            expected_source_contains="academic-calendar.wlu.ca",
        ))
    return items


